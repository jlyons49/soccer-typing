// Fallback generator for lengths
export function getWordsOfLength(len) {
  if (WORD_POOLS[len] && WORD_POOLS[len].length > 0) return WORD_POOLS[len];
  const keys = Object.keys(WORD_POOLS).map(Number).sort((a, b) => a - b);
  if (len <= keys[0]) return WORD_POOLS[keys[0]];
  if (len >= keys[keys.length - 1]) return WORD_POOLS[keys[keys.length - 1]];
  // Find closest length pool
  let bestKey = keys[0];
  let bestDiff = Math.abs(len - bestKey);
  for (const k of keys) {
    const d = Math.abs(len - k);
    if (d < bestDiff) {
      bestDiff = d;
      bestKey = k;
    }
  }
  return WORD_POOLS[bestKey];
}

// Generate a single random word for Dribbling Drill mode
export function generateDribbleWord(difficultyConfig, excludeWord = '') {
  const minLen = difficultyConfig.dribbleMinLen || 3;
  const maxLen = difficultyConfig.dribbleMaxLen || 5;
  const targetLen = Math.floor(Math.random() * (maxLen - minLen + 1)) + minLen;
  const pool = getWordsOfLength(targetLen);
  const candidates = pool.filter(w => w !== excludeWord);
  if (candidates.length === 0) return pool[0] || 'DRIBBLE';
  return candidates[Math.floor(Math.random() * candidates.length)];
}

// Generate distinct target words for a Shooting Practice round
export function generateRoundTargets(difficultyConfig, zonesList = GOAL_ZONES) {
  const diff = difficultyConfig;
  const targetCount = diff.targetCount || 4;
  const activeZones = zonesList.slice(0, targetCount);

  const chosenTargets = [];
  const usedFirstLetters = new Set();
  const usedWords = new Set();

  activeZones.forEach(zone => {
    const minLen = zone.isCorner ? diff.cornerMinLen : diff.centerMinLen;
    const maxLen = zone.isCorner ? diff.cornerMaxLen : diff.centerMaxLen;

    const targetLen = Math.floor(Math.random() * (maxLen - minLen + 1)) + minLen;
    const pool = getWordsOfLength(targetLen);

    const candidates = [...pool].sort(() => Math.random() - 0.5);

    let selectedWord = null;
    for (const w of candidates) {
      const firstChar = w[0].toUpperCase();
      if (!usedFirstLetters.has(firstChar) && !usedWords.has(w)) {
        selectedWord = w;
        break;
      }
    }

    if (!selectedWord) {
      for (const w of candidates) {
        if (!usedWords.has(w)) {
          selectedWord = w;
          break;
        }
      }
    }

    if (!selectedWord) {
      selectedWord = candidates[0] || 'GOAL';
    }

    usedFirstLetters.add(selectedWord[0].toUpperCase());
    usedWords.add(selectedWord);

    chosenTargets.push({
      zone,
      word: selectedWord.toUpperCase(),
      typedIndex: 0,
      completed: false,
      points: Math.round(100 * zone.scoreMultiplier * diff.pointsMultiplier)
    });
  });

  return chosenTargets;
}

// Generate a single letter for Touch Practice mode based on difficulty tier
export function generateTouchLetter(difficultyConfig, excludeLetter = '') {
  const pool = difficultyConfig.touchKeys || ['A', 'S', 'D', 'F', 'J', 'K', 'L'];
  const candidates = pool.filter(l => l !== excludeLetter);
  if (candidates.length === 0) return pool[0] || 'A';
  return candidates[Math.floor(Math.random() * candidates.length)];
}

